begin;

-- In-app notifications are private to the intended recipient. Client roles receive
-- no direct table privileges; all reads and updates go through recipient-scoped RPCs.
create table if not exists public.learning_notifications (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  recipient_user_id uuid not null references public.users(id) on delete cascade,
  actor_user_id uuid references public.users(id) on delete set null,
  notification_type text not null check (notification_type in (
    'marketplace.booking_requested',
    'marketplace.booking_confirmed',
    'marketplace.booking_declined',
    'marketplace.booking_cancelled'
  )),
  title text not null check (length(trim(title)) between 1 and 120),
  body text not null check (length(trim(body)) between 1 and 500),
  resource_type text not null check (resource_type in ('marketplace_booking')),
  resource_id uuid not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists learning_notifications_recipient_created_idx
  on public.learning_notifications (recipient_user_id, created_at desc);

create index if not exists learning_notifications_unread_idx
  on public.learning_notifications (recipient_user_id, created_at desc)
  where read_at is null;

alter table public.learning_notifications enable row level security;
revoke all on public.learning_notifications from anon, authenticated;

create or replace function public.list_learning_notifications(p_limit integer default 50)
returns table (
  id uuid,
  organization_id uuid,
  notification_type text,
  title text,
  body text,
  resource_type text,
  resource_id uuid,
  read_at timestamptz,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
stable
as $function$
declare
  v_user_id uuid;
begin
  select u.id into v_user_id
  from public.users u
  where u.auth_user_id = (select auth.uid())
  limit 1;

  if v_user_id is null then
    raise exception 'Authenticated user profile not found';
  end if;

  return query
  select n.id, n.organization_id, n.notification_type, n.title, n.body,
         n.resource_type, n.resource_id, n.read_at, n.created_at
  from public.learning_notifications n
  where n.recipient_user_id = v_user_id
  order by n.created_at desc, n.id desc
  limit greatest(1, least(coalesce(p_limit, 50), 100));
end;
$function$;

create or replace function public.count_unread_learning_notifications()
returns bigint
language plpgsql
security definer
set search_path = ''
stable
as $function$
declare
  v_user_id uuid;
  v_count bigint;
begin
  select u.id into v_user_id
  from public.users u
  where u.auth_user_id = (select auth.uid())
  limit 1;

  if v_user_id is null then
    raise exception 'Authenticated user profile not found';
  end if;

  select count(*) into v_count
  from public.learning_notifications n
  where n.recipient_user_id = v_user_id
    and n.read_at is null;

  return coalesce(v_count, 0);
end;
$function$;

create or replace function public.mark_learning_notification_read(p_notification_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user_id uuid;
  v_updated integer;
begin
  select u.id into v_user_id
  from public.users u
  where u.auth_user_id = (select auth.uid())
  limit 1;

  if v_user_id is null then
    raise exception 'Authenticated user profile not found';
  end if;

  update public.learning_notifications n
  set read_at = coalesce(n.read_at, now())
  where n.id = p_notification_id
    and n.recipient_user_id = v_user_id;

  get diagnostics v_updated = row_count;
  return v_updated = 1;
end;
$function$;

create or replace function public.mark_all_learning_notifications_read()
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user_id uuid;
  v_updated integer;
begin
  select u.id into v_user_id
  from public.users u
  where u.auth_user_id = (select auth.uid())
  limit 1;

  if v_user_id is null then
    raise exception 'Authenticated user profile not found';
  end if;

  update public.learning_notifications n
  set read_at = now()
  where n.recipient_user_id = v_user_id
    and n.read_at is null;

  get diagnostics v_updated = row_count;
  return v_updated;
end;
$function$;

-- Booking events are generated by the database so browser retries cannot silently
-- omit notifications. The event contains no student personal details.
create or replace function public.notify_learning_marketplace_booking_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_teacher_user_id uuid;
  v_offering_title text;
  v_actor_user_id uuid;
  v_recipient_user_id uuid;
  v_type text;
  v_title text;
  v_body text;
begin
  select offer.teacher_user_id, offer.title
    into v_teacher_user_id, v_offering_title
  from public.learning_marketplace_offerings offer
  where offer.id = new.offering_id
    and offer.organization_id = new.organization_id;

  if v_teacher_user_id is null then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if new.status <> 'requested' then
      return new;
    end if;
    v_actor_user_id := new.requester_user_id;
    v_recipient_user_id := v_teacher_user_id;
    v_type := 'marketplace.booking_requested';
    v_title := 'New extra-class request';
    v_body := 'A learner or parent has requested: ' || v_offering_title;
  elsif tg_op = 'UPDATE' and new.status is distinct from old.status then
    select u.id into v_actor_user_id
    from public.users u
    where u.auth_user_id = (select auth.uid())
    limit 1;

    if new.status = 'accepted' then
      v_type := 'marketplace.booking_confirmed';
      v_title := 'Extra class confirmed';
      v_body := 'The teacher confirmed: ' || v_offering_title;
      v_recipient_user_id := new.requester_user_id;
    elsif new.status = 'declined' then
      v_type := 'marketplace.booking_declined';
      v_title := 'Extra-class request declined';
      v_body := 'The teacher could not accept: ' || v_offering_title;
      v_recipient_user_id := new.requester_user_id;
    elsif new.status = 'cancelled' then
      v_type := 'marketplace.booking_cancelled';
      v_title := 'Extra class cancelled';
      v_body := 'A booking was cancelled: ' || v_offering_title;
      if v_actor_user_id = new.requester_user_id then
        v_recipient_user_id := v_teacher_user_id;
      else
        v_recipient_user_id := new.requester_user_id;
      end if;
    else
      return new;
    end if;
  else
    return new;
  end if;

  if v_recipient_user_id is not null
     and v_recipient_user_id is distinct from v_actor_user_id then
    insert into public.learning_notifications (
      organization_id, recipient_user_id, actor_user_id,
      notification_type, title, body, resource_type, resource_id
    ) values (
      new.organization_id, v_recipient_user_id, v_actor_user_id,
      v_type, v_title, v_body, 'marketplace_booking', new.id
    );
  end if;

  return new;
end;
$function$;

drop trigger if exists learning_marketplace_booking_notify_insert
  on public.learning_marketplace_booking_requests;
create trigger learning_marketplace_booking_notify_insert
after insert on public.learning_marketplace_booking_requests
for each row execute function public.notify_learning_marketplace_booking_event();

drop trigger if exists learning_marketplace_booking_notify_status
  on public.learning_marketplace_booking_requests;
create trigger learning_marketplace_booking_notify_status
after update of status on public.learning_marketplace_booking_requests
for each row execute function public.notify_learning_marketplace_booking_event();

revoke all on function public.list_learning_notifications(integer) from public, anon;
revoke all on function public.count_unread_learning_notifications() from public, anon;
revoke all on function public.mark_learning_notification_read(uuid) from public, anon;
revoke all on function public.mark_all_learning_notifications_read() from public, anon;
revoke all on function public.notify_learning_marketplace_booking_event() from public, anon, authenticated;

grant execute on function public.list_learning_notifications(integer) to authenticated;
grant execute on function public.count_unread_learning_notifications() to authenticated;
grant execute on function public.mark_learning_notification_read(uuid) to authenticated;
grant execute on function public.mark_all_learning_notifications_read() to authenticated;

commit;
