insert into public.learning_objective_alignments(objective_id,curriculum_id,grade_level_id,sequence_no,required,indicator_classification,notes)
select o.id,c.id,g.id,s.seq,s.required,s.classification,
'OBEC 2021 must-know/should-know prioritisation; official indicator wording; Thai Basic Education Core Curriculum B.E.2551.'
from seed s
join public.learning_subjects sub on sub.code='HEALTH-PE'
join public.learning_skills sk on sk.subject_id=sub.id and sk.code='HEALTH-PE'
join public.learning_topics t on t.skill_id=sk.id and t.code=s.standard_code
join public.learning_objectives o on o.topic_id=t.id and o.code=s.code
join public.learning_curricula c on c.id='a366b931-63be-49b5-8433-dbea2691a055'
join public.learning_grade_levels g on g.curriculum_id=c.id and g.code=s.grade_code
on conflict(objective_id,curriculum_id,grade_level_id) do update set
sequence_no=excluded.sequence_no,required=excluded.required,
indicator_classification=excluded.indicator_classification,notes=excluded.notes,updated_at=now();
