 case when seed.is_required then 'OBEC 2021 classification: must know' else 'OBEC 2021 classification: should know' end
from seed
join public.learning_topics t on t.code=seed.standard_code
join public.learning_skills sk on sk.id=t.skill_id
join public.learning_subjects s on s.id=sk.subject_id and s.code='THAI-LANGUAGE'
join public.learning_objectives o on o.topic_id=t.id and o.code=seed.objective_code
join public.learning_curricula c on c.code='TH-BASIC-CORE-2008-2017'
join public.learning_grade_levels gl on gl.curriculum_id=c.id and gl.code=seed.grade_code
on conflict(objective_id,curriculum_id,grade_level_id) do update set
